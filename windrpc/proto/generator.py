def resolve_type_name(type_name, current_service_name, spec_data, package_prefix):
    """
    타입 이름을 올바른 전체 경로로 변환합니다.
    - 'types.Empty' -> 'package.types.Empty'
    - 'Empty' -> 'package.types.Empty' (공용 타입일 경우)
    - 'PixelData' -> 'PixelData' (같은 서비스 내 지역 타입일 경우)
    """
    # if not isinstance(type_name, str):
    #     return to_pascal_case(str(type_name))
    # print(declared_all_types)

    scalar_types = {'double', 'float', 'int32', 'int64', 'uint32', 'uint64', 'sint32',
                    'sint64', 'fixed32', 'fixed64', 'sfixed32', 'sfixed64', 'bool', 'string', 'bytes'}
    if type_name.lower() in scalar_types:
        return type_name.lower()

    # # 1. 모든 알려진 사용자 정의 타입을 {단순이름: 전체경로} 맵으로 사전 계산
    # # common_types = {to_pascal_case(m.get('name')) for m in spec_data.get('types', {}).get('messages', [])} | \
    # #                {to_pascal_case(e.get('name')) for e in spec_data.get('types', {}).get('enums', [])}
    # common_types = {m.get('name') for m in spec_data.get('types', {}).get('messages', [])} | \
    #                {e.get('name') for e in spec_data.get('types', {}).get('enums', [])}

    # another_types = set()
    # local_types = set()
    # # if current_service_name:
    # for svc in spec_data.get('services', []):
    #     if svc.get('name') == current_service_name:
    #         # local_types = {to_pascal_case(m.get('name')) for m in svc.get('messages', [])} | \
    #         #               {to_pascal_case(e.get('name')) for e in svc.get('enums', [])}
    #         # break
    #         local_types = {(m.get('name')) for m in svc.get('messages', [])} | \
    #                         {(e.get('name')) for e in svc.get('enums', [])}
    #     else :
    #         another_types |= {(m.get('name')) for m in svc.get('messages', [])} | \
    #                         {(e.get('name')) for e in svc.get('enums', [])}

    # 2. 입력된 타입 이름의 가장 마지막 부분(실제 타입명)을 추출
    # simple_name = to_pascal_case(type_name.split('.')[-1])
    simple_name = type_name.split('.')[-1]

    # 3. 타입 확인 및 전체 경로 반환
    # 지역 타입이 우선순위가 가장 높음
    # if simple_name in local_types:
    if current_service_name is not None and simple_name in declared_all_types[current_service_name]:
        return simple_name

    # 그 다음 공용 타입
    # if simple_name in common_types:
    if simple_name in declared_all_types["types"]:
        return f"{package_prefix}.windrpc.types.{simple_name}"

    # 마지막 다른 서비스타입
    parts = type_name.split('.')
    sub_package_name = parts[-2] if len(parts) >= 2 else None
    if sub_package_name is not None:
        if simple_name in declared_all_types[sub_package_name]:
            return f"{package_prefix}.windrpc.service.{type_name}"

    # 그 외 (다른 서비스의 타입 등)는 입력된 대로 반환 (마지막 부분은 PascalCase)
    parts = type_name.split('.')
    parts[-1] = simple_name
    return ".".join(parts)


# --- .proto 파일 생성 함수들 ---

def generate_types_proto(spec_data, package_prefix):
    content = [get_generated_file_header(), 'syntax = "proto3";\n',
               f"package {package_prefix}.windrpc.types;\n"]
    resolved_type_names = []
    types_spec = spec_data.get('types', {})
    content.append(generate_enums_from_spec(types_spec.get('enums', [])))
    for msg_def in types_spec.get('messages', []):
        content.append(f"message {to_pascal_case(msg_def['name'])} {{")
        reserved_stmt = generate_reserved_statement(
            msg_def.get('reserved', []))
        if reserved_stmt:
            content.append(reserved_stmt)
        for oneof_def in msg_def.get('oneofs', []):
            content.append(f"  oneof {oneof_def['name']} {{")
            for field in oneof_def.get('fields', []):
                field['type'] = resolve_type_name(
                    field['type'], None, spec_data, package_prefix)
                resolved_type_names.append(field['type'])
                content.append(f"  {format_field(field)}")
            content.append("  }")
        for field in msg_def.get('fields', []):
            field['type'] = resolve_type_name(
                field['type'], None, spec_data, package_prefix)
            resolved_type_names.append(field['type'])
            content.append(format_field(field))
        content.append("}\n")

    import_paths = generate_import_paths(resolved_type_names)
    if len(import_paths) > 0:
        content.insert(3, "\n".join(import_paths))

    return "\n".join(content)


def generate_service_proto(service_spec, spec_data, package_prefix):
    service_name = service_spec['name']
    svc_id = service_spec.get('id', 0)
    content = [get_generated_file_header(), 'syntax = "proto3";\n',
               f"package {package_prefix}.windrpc.service.{service_name};\n"]

    doc_lines = ["/**"]
    doc_lines.append(f" * Service: {service_name} (ID: {svc_id})")
    doc_lines.append(" * RPC Methods:")
    for rpc in service_spec.get('rpcs', []):
        rpc_type = rpc.get('type', '').upper()
        rpc_name = rpc['name']
        rpc_id = rpc['id']
        combined_id = (svc_id << 8) | rpc_id
        desc = rpc.get('description', rpc.get('summary', ''))
        desc_str = f" - {desc}" if desc else ""
        if rpc_type == 'REQUEST_ONLY':
            doc_lines.append(f" *  - {rpc_name} (0x{combined_id:04X}): param={rpc.get('command', 'types.Empty')}, return=void{desc_str}")
        elif rpc_type == 'REQUEST_RESPONSE':
            doc_lines.append(f" *  - {rpc_name} (0x{combined_id:04X}): param={rpc.get('command', 'types.Empty')}, return={rpc.get('result', 'types.Empty')}{desc_str}")
        elif rpc_type == 'NOTIFICATION':
            event_combined_id = (svc_id << 8) | (rpc_id | 0x80)
            doc_lines.append(f" *  - subscribe_{rpc_name} (0x{combined_id:04X}): param=types.Subscribe, return=types.Empty")
            doc_lines.append(f" *  - {rpc_name} Event (0x{event_combined_id:04X}): event={rpc.get('event', 'types.Empty')}{desc_str}")
    doc_lines.append(" */\n")
    content.append("\n".join(doc_lines))

    imports_to_add = set()
    all_type_names = []
    resolved_type_names = []

    for msg_def in service_spec.get('messages', []):
        for field in msg_def.get('fields', []):
            all_type_names.append(field.get('type'))
        for oneof in msg_def.get('oneofs', []):
            for field in oneof.get('fields', []):
                all_type_names.append(field.get('type'))

    for rpc in service_spec.get('rpcs', []):
        all_type_names.extend(
            [rpc.get('command'), rpc.get('result'), rpc.get('event')])

    scalar_types = {'double', 'float', 'int32', 'int64', 'uint32', 'uint64', 'sint32',
                    'sint64', 'fixed32', 'fixed64', 'sfixed32', 'sfixed64', 'bool', 'string', 'bytes'}

    for type_name in filter(None, all_type_names):
        if not isinstance(type_name, str) or type_name.lower() in scalar_types:
            continue
        resolved_name = resolve_type_name(
            type_name, service_name, spec_data, package_prefix)
        resolved_type_names.append(resolved_name)

    if imports_to_add:
        content.append("")
        content.extend(sorted(list(imports_to_add)))
        content.append("")
    content.append(generate_enums_from_spec(service_spec.get('enums', [])))

    for msg_def in service_spec.get('messages', []):
        content.append(f"message {to_pascal_case(msg_def['name'])} {{")
        reserved_stmt = generate_reserved_statement(
            msg_def.get('reserved', []))
        if reserved_stmt:
            content.append(reserved_stmt)
        for oneof_def in msg_def.get('oneofs', []):
            content.append(f"  oneof {oneof_def['name']} {{")
            for field in oneof_def.get('fields', []):
                field['type'] = resolve_type_name(
                    field['type'], service_name, spec_data, package_prefix)
                content.append(f"  {format_field(field)}")
                resolved_type_names.append(field['type'])
            content.append("  }")
        for field in msg_def.get('fields', []):
            field['type'] = resolve_type_name(
                field['type'], service_name, spec_data, package_prefix)
            content.append(format_field(field))
            resolved_type_names.append(field['type'])
        content.append("}\n")

    command_rpcs, result_rpcs, event_rpcs = [], [], []
    for rpc in service_spec.get('rpcs', []):
        rpc_type = rpc.get('type', '').upper()
        rpc_id, rpc_name = rpc['id'], rpc['name']
        if rpc_type in ['REQUEST_ONLY', 'REQUEST_RESPONSE']:
            command_type = resolve_type_name(
                rpc['command'], service_name, spec_data, package_prefix)
            command_rpcs.append(f"    {command_type} {rpc_name} = {rpc_id};")
            resolved_type_names.append(command_type)
        if rpc_type == 'REQUEST_RESPONSE':
            result_type = resolve_type_name(
                rpc['result'], service_name, spec_data, package_prefix)
            result_rpcs.append(f"    {result_type} {rpc_name} = {rpc_id};")
            resolved_type_names.append(result_type)
        if rpc_type == 'NOTIFICATION':
            subscribe_command_name = f"subscribe_{rpc_name}"
            subscribe_type = resolve_type_name(
                f"{package_prefix}.windrpc.types.Subscribe", service_name, spec_data, package_prefix)
            resolved_type_names.append(subscribe_type)
            ack_type = resolve_type_name(
                f"{package_prefix}.windrpc.types.Empty", service_name, spec_data, package_prefix)
            resolved_type_names.append(ack_type)
            command_rpcs.append(
                f"    {subscribe_type} {subscribe_command_name} = {rpc_id};")
            result_rpcs.append(
                f"    {ack_type} {subscribe_command_name} = {rpc_id};")
            event_type = resolve_type_name(
                rpc['event'], service_name, spec_data, package_prefix)
            resolved_type_names.append(event_type)
            event_rpcs.append(f"    {event_type} {rpc_name} = {rpc_id};")


    import_paths = generate_import_paths(resolved_type_names)
    if len(import_paths) > 0:
        content.insert(3, "\n".join(import_paths))

    return "\n".join(content)


def _format_rpc_doc_comment(svc_name, svc_id, rpc):
    rpc_type = rpc.get('type', '').upper()
    rpc_name = rpc['name']
    rpc_id = rpc['id']
    desc = rpc.get('description', rpc.get('summary', 'No description provided.'))
    combined_id = combine_ids(svc_id, rpc_id)

    lines = []
    lines.append("  /**")
    lines.append(f"   * @service {svc_name}")
    lines.append(f"   * @rpc {rpc_name}")
    lines.append(f"   * @type {rpc_type}")
    lines.append(f"   * @id 0x{combined_id:04X} ({combined_id})")
    lines.append(f"   * @summary {desc}")

    if rpc_type in ['REQUEST_ONLY', 'REQUEST_RESPONSE']:
        lines.append(f"   * @param command {rpc.get('command', 'types.Empty')}")
    if rpc_type == 'REQUEST_RESPONSE':
        lines.append(f"   * @return result {rpc.get('result', 'types.Empty')}")
    elif rpc_type == 'REQUEST_ONLY':
        lines.append("   * @return void")
    elif rpc_type == 'NOTIFICATION':
        lines.append(f"   * @param subscribe types.Subscribe (enable=true/false)")
        lines.append(f"   * @event notification {rpc.get('event', 'types.Empty')}")

    lines.append("   */")
    return "\n".join(lines)


def generate_windrpc_proto(spec_data, package_prefix):

    content = [get_generated_file_header(), 'syntax = "proto3";\n',
               f'package {package_prefix}.windrpc.core;\n']
    for svc in spec_data['services']:
        content.append(
            f'import "{package_prefix}/windrpc/service/{svc["name"]}.proto";')
    content.append(f'import "{package_prefix}/windrpc/types/types.proto";\n')
    content.append(f"enum RpcId {{\n  RPC_ID_UNKNOWN = 0;\n")
    for svc in spec_data.get('services', []):
        svc_name = svc['name']
        svc_id = svc['id']
        for rpc in svc.get('rpcs', []):
            rpc_type = rpc.get('type', '').upper()
            doc_comment = _format_rpc_doc_comment(svc_name, svc_id, rpc)
            content.append(doc_comment)
            if rpc_type == 'NOTIFICATION':
                sub_name = f"subscribe_{rpc['name']}"
                content.append(
                    f"  RPC_ID_{svc_name.upper()}_{sub_name.upper()} = {combine_ids(svc_id, rpc['id'])};\n")
                event_combined_id = (svc_id << 8) | (rpc['id'] | 0x80)
                content.append(
                    f"  RPC_ID_{svc_name.upper()}_{rpc['name'].upper()} = {event_combined_id};\n")
            else:
                content.append(
                    f"  RPC_ID_{svc_name.upper()}_{rpc['name'].upper()} = {combine_ids(svc_id, rpc['id'])};\n")
    content.append('}\n')

    return "\n".join(content)


def generate(core_spec_path, user_spec_path, output_dir, verbose=False, strict=False):
    try:
        with open(core_spec_path, 'r', encoding='utf-8') as f:
            core_spec_data = yaml.load(f, Loader=LineNumberLoader)
        with open(user_spec_path, 'r', encoding='utf-8') as f:
            user_spec_data = yaml.load(f, Loader=LineNumberLoader)
    except FileNotFoundError as e:
        print(f"Error: Spec file not found - {e}", file=sys.stderr)
        sys.exit(1)
    except yaml.YAMLError as e:
        print(f"Error parsing YAML file: {e}", file=sys.stderr)
        sys.exit(1)

    spec_data = merge_specs(core_spec_data, user_spec_data)

    spec_validator.validate(spec_data, verbose=verbose, strict=strict)
    print("YAML Specification validation successful.")

    package_name = spec_data.get('package', 'default_package')
    output_path = os.path.join(output_dir, f"{package_name}/windrpc")
    os.makedirs(output_path, exist_ok=True)

    get_all_types(spec_data)

    print("\nGenerating .proto files...")

    # types.proto
    types_path = os.path.join(output_path, "types")
    os.makedirs(types_path, exist_ok=True)
    with open(os.path.join(types_path, "types.proto"), 'w', encoding='utf-8') as f:
        f.write(generate_types_proto(spec_data, package_name))
    print(f"Generated {os.path.join(types_path, 'types.proto')}")

    # windrpc/service/*.proto
    service_path = os.path.join(output_path, "service")
    os.makedirs(service_path, exist_ok=True)
    for service_spec in spec_data.get('services', []):
        file_path = os.path.join(service_path, f"{service_spec['name']}.proto")
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(generate_service_proto(
                service_spec, spec_data, package_name))
        print(f"Generated {file_path}")

    # windrpc/core/windrpc.proto
    core_path = os.path.join(output_path, "core")
    os.makedirs(core_path, exist_ok=True)
    with open(os.path.join(core_path, "windrpc.proto"), 'w', encoding='utf-8') as f:
        f.write(generate_windrpc_proto(spec_data, package_name))
    print(f"Generated {os.path.join(core_path, 'windrpc.proto')}")

    print("\nGenerating Nanopb options files...")
    options_generator.generate_options_files(
        spec_data, output_path, package_name, verbose=verbose)
    print("Nanopb options file generation complete.")

    print("\nProto file generation complete.")
