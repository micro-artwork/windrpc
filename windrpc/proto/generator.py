def get_generated_file_header():
    """자동 생성된 .proto 파일의 표준 헤더를 반환합니다."""
    return "// Copyright (c) 2026 WindRPC\n//\n// SPDX-License-Identifier: MIT\n//\n// This file is automatically generated. Do not modify.\n"

# NOTE: proto syntax
# Although Protobuf Editions (e.g. edition = "2023") is the modern replacement
# for proto2/proto3, the Nanopb library (nanopb/nanopb) used on the C MCU side
# does not currently (as of 2026) support Protobuf Editions.
# The nanopb generator plugin cannot interpret edition-based feature flags,
# so we maintain syntax = "proto3" until nanopb officially supports Editions.


def format_field(field):
    """단일 Protobuf 필드 라인을 포맷합니다."""
    prop = field.get('property', '').strip()
    prefix = f"{prop} " if prop in ["repeated", "optional"] else ""
    field_str = f"  {prefix}{field['type']} {field['name']} = {field['number']};"
    if 'description' in field:
        field_str += f" // {field['description']}"
    return field_str


def generate_reserved_statement(yaml_reserved_list):
    if not yaml_reserved_list:
        return None
    numbers, names = [], []
    for item in yaml_reserved_list:
        if isinstance(item, int):
            numbers.append(str(item))
        elif isinstance(item, str):
            if ' to ' in item:
                numbers.append(item)
            else:
                names.append(f'"{item}"')
    statements = []
    if numbers:
        statements.append(f"  reserved {', '.join(numbers)};")
    if names:
        statements.append(f"  reserved {', '.join(names)};")
    return "\n".join(statements) if statements else None


def format_enum_item(item, prefix):
    """enum 멤버를 proto 스타일로 포맷합니다. prefix 자동 적용 포함."""
    name = apply_enum_prefix(item['name'], prefix)
    return f"  {name} = {item['value']};"


def generate_enums_from_spec(enums_to_process):
    content = []
    for enum_def in enums_to_process:
        content.append(f"enum {to_pascal_case(enum_def['name'])} {{")
        # Proto 스타일 가이드: enum 값 접두어 자동 적용
        # spec의 'prefix' 키 우선, 없으면 enum 타입명에서 자동 계산
        explicit_prefix = enum_def.get('prefix', None)
        prefix = enum_value_prefix(enum_def['name'], explicit_prefix)
        current_value = 0
        for item in enum_def['members']:
            item['value'] = item.get('value', current_value)
            content.append(format_enum_item(item, prefix))
            current_value = item['value'] + 1
        reserved_stmt = generate_reserved_statement(
            enum_def.get('reserved', []))
        if reserved_stmt:
            content.append(reserved_stmt)
        content.append('}\n')
    return "\n".join(content)


def get_all_types(spec_data):
    declared_all_types['types'] = {m.get('name') for m in spec_data.get('types', {}).get('messages', [])} | \
        {e.get('name') for e in spec_data.get('types', {}).get('enums', [])}

    for svc in spec_data.get('services', []):
        declared_all_types[svc.get('name')] = {(m.get('name')) for m in svc.get('messages', [])} | \
            {(e.get('name')) for e in svc.get('enums', [])}

    # print(declared_all_types)


def generate_import_paths(type_names):
    import_paths = []
    scalar_types = {'double', 'float', 'int32', 'int64', 'uint32', 'uint64', 'sint32',
                    'sint64', 'fixed32', 'fixed64', 'sfixed32', 'sfixed64', 'bool', 'string', 'bytes'}
    for type_name in type_names:
        if type_name in scalar_types:
            continue
        parts = type_name.split('.')
        # print(type_name)
        if len(parts) >= 2:
            new_parts = parts[:-1]
            if new_parts[-1] == 'types':
                new_parts[-1] += '/types.proto'
            else:
                new_parts[-1] += '.proto'
            import_path = f'import "{"/".join(new_parts)}";'
            if import_path not in import_paths:
                import_paths.append(import_path)
    # print(import_paths)
    return import_paths


